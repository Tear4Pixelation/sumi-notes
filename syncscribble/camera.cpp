static void appendHuffTable(std::vector<unsigned char>& seg, unsigned char classAndId,
    const unsigned char* bits, const unsigned char* values, size_t nvalues)
{
  seg.push_back(classAndId);
  seg.insert(seg.end(), bits, bits + 16);
  seg.insert(seg.end(), values, values + nvalues);
}

static const std::vector<unsigned char>& standardDHT()
{
  static std::vector<unsigned char> seg;
  if(seg.empty()) {
    seg = {0xFF, 0xC4, 0, 0};
    appendHuffTable(seg, 0x00, dcLumBits, dcValues, sizeof(dcValues));
    appendHuffTable(seg, 0x01, dcChromBits, dcValues, sizeof(dcValues));
    appendHuffTable(seg, 0x10, acLumBits, acLumValues, sizeof(acLumValues));
    appendHuffTable(seg, 0x11, acChromBits, acChromValues, sizeof(acChromValues));
    size_t seglen = seg.size() - 2;  // the length field counts itself but not the marker
    seg[2] = (unsigned char)(seglen >> 8);
    seg[3] = (unsigned char)(seglen & 0xFF);
  }
  return seg;
}

Image decodeMjpegFrame(const unsigned char* data, size_t len)
{
  if(len < 4 || data[0] != 0xFF || data[1] != 0xD8)
    return Image(0, 0);
  // walk the header segments up to the start of scan, looking for a DHT
  size_t pos = 2;
  while(pos + 4 <= len && data[pos] == 0xFF) {
    unsigned char marker = data[pos+1];
    if(marker == 0xDA)
      break;
    if(marker == 0xC4)
      return Image::decodeBuffer(data, len, Image::JPEG);
    pos += 2 + ((size_t(data[pos+2]) << 8) | data[pos+3]);
  }
  if(pos + 2 > len || data[pos] != 0xFF || data[pos+1] != 0xDA)
    return Image::decodeBuffer(data, len, Image::JPEG);  // not a layout we understand; let stb try
  const std::vector<unsigned char>& dht = standardDHT();
  std::vector<unsigned char> fixed;
  fixed.reserve(len + dht.size());
  fixed.insert(fixed.end(), data, data + pos);
  fixed.insert(fixed.end(), dht.begin(), dht.end());
  fixed.insert(fixed.end(), data + pos, data + len);
  return Image::decodeBuffer(fixed.data(), fixed.size(), Image::JPEG);
}

static inline unsigned char clampByte(int val) { return val < 0 ? 0 : val > 255 ? 255 : (unsigned char)val; }

void yuyvToRGBA(const unsigned char* src, int width, int height, int srcStride, unsigned char* dst)
{
  for(int row = 0; row < height; ++row) {
    const unsigned char* in = src + size_t(row)*srcStride;
    unsigned char* out = dst + size_t(row)*width*4;
    for(int col = 0; col + 1 < width; col += 2, in += 4) {
      int chromaU = in[1] - 128, chromaV = in[3] - 128;
      int redOffset = 409*chromaV + 128;
      int greenOffset = -100*chromaU - 208*chromaV + 128;
      int blueOffset = 516*chromaU + 128;
      for(int half = 0; half < 2; ++half) {
        int luma = 298*(in[half*2] - 16);
        *out++ = clampByte((luma + redOffset) >> 8);
        *out++ = clampByte((luma + greenOffset) >> 8);
        *out++ = clampByte((luma + blueOffset) >> 8);
        *out++ = 255;
      }
    }
  }
}

