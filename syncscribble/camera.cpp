bool Camera::takeFrame(Image* frame)
{
  std::lock_guard<std::mutex> lock(mutex);
  if(!hasNew)
    return false;
  *frame = std::move(latest);
  latest = Image(0, 0);
  hasNew = false;
  return true;
}

std::string Camera::error() const
{
  std::lock_guard<std::mutex> lock(mutex);
  return errorMsg;
}

void Camera::publishFrame(Image&& frame)
{
  if(frame.isNull() || frame.width <= 0 || frame.height <= 0)
    return;
  std::lock_guard<std::mutex> lock(mutex);
  latest = std::move(frame);
  hasNew = true;
}

void Camera::setError(const std::string& msg)
{
  std::lock_guard<std::mutex> lock(mutex);
  errorMsg = msg;
}

